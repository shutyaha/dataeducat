import random

answers = [
    'Бесспорно', 'Предрешено', 'Никаких сомнений', 'Определённо да',
    'Можешь быть уверен в этом', 'Мне кажется - да', 'Вероятнее всего',
    'Хорошие перспективы', 'Знаки говорят - да', 'Да',
    'Пока неясно, попробуй снова', 'Спроси позже', 'Лучше не рассказывать',
    'Сейчас нельзя предсказать', 'Сконцентрируйся и спроси опять',
    'Даже не думай', 'Мой ответ - нет', 'По моим данным - нет',
    'Перспективы не очень хорошие', 'Весьма сомнительно'
]

print('Привет, Мир! Я магический шар, и я знаю ответ на любой твой вопрос.')

name = input('Как тебя зовут: ').strip()
while not name:
    name = input('Пожалуйста, введи своё имя: ').strip()

print(f'Привет, {name}!')

def magic_ball_8():
    questions_count = 0

    while True:
        question = input('\nКакой вопрос тебя интересует? (или "q" для выхода): ').strip()

        if question.lower() == 'q':
            print(f'\nВозвращайся, если возникнут новые вопросы, {name}!')
            print(f'Всего ты задал вопросов: {questions_count}')
            break

        if not question:
            print('Похоже, вопрос пустой. Попробуй ещё раз.')
            continue

        questions_count += 1
        answer = random.choice(answers)
        print(f'🔮 Ответ магического шара: {answer}')


magic_ball_8()


